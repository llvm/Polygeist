#!/usr/bin/env python3
"""Build lib_v2: raise every netlib reference spec and emit kernel_library_v2.

Usage:
  build_lib_v2.py [--recipe production|campaign] [-j N] [--timeout S]
                  [--only SPEC ...] [--no-raise]

For every spec in every fragment generic_solver/lib_v2/manifest/*.json
(including fragments written by other agents) this script

  1. writes the specialised C wrapper  raised/<spec>.c
     (#define NETLIB_SPEC <spec>, the manifest `defines`, #include ref_c),
  2. raises it with scripts/correctness/lib_v2/recipe.py -- the same module
     that raises application code -- producing raised/<spec>.mlir,
     raised/<spec>_linalg.mlir and raised/<spec>_debuf.mlir,
  3. classifies the result (RAISED / PARTIAL / NOT_RAISED / FAIL_*),
  4. converts each fully raised function into a tensor-form `kernel.defn`
     whose body is the raised function body, verbatim except for the
     memref<->tensor boundary (see `to_defn`), and verifies it parses,
  5. writes generic_solver/lib_v2/RAISE_STATUS.md and
     generic_solver/kernel_library_v2.mlir.

Per-routine knowledge lives only in ref_c/ and manifest/.
"""
