@dataclass
class Spec:
    name: str
    routine: str
    fragment: Path
    ref_c: Path
    defines: dict
    args: list
    target: dict
    assumptions: list
    deviations: list
    returns: str | None = None
    raw: dict = field(default_factory=dict)


def load_specs() -> list[Spec]:
    specs: list[Spec] = []
    seen: set[str] = set()
    for frag in sorted(MANIFEST.glob("*.json")):
        try:
            data = json.loads(frag.read_text())
        except json.JSONDecodeError as e:
            print(f"warning: cannot parse {frag}: {e}", file=sys.stderr)
            continue
        routine = data.get("routine", frag.stem)
        ref_c = REF_C / data.get("ref_c", f"{routine}.c")
        for s in data.get("specs", []):
            name = s["name"]
            if name in seen:
                print(f"warning: duplicate spec {name} in {frag}", file=sys.stderr)
                continue
            seen.add(name)
            specs.append(Spec(
                name=name, routine=routine, fragment=frag,
                ref_c=REF_C / s["ref_c"] if "ref_c" in s else ref_c,
                defines=s.get("defines", {}), args=s.get("args", []),
                target=s.get("target", {}), assumptions=s.get("assumptions", []),
                deviations=s.get("deviations", []), returns=s.get("returns"), raw=s))
    return specs


def write_wrapper(spec: Spec) -> Path:
    RAISED.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Generated by scripts/correctness/lib_v2/build_lib_v2.py -- do not edit.",
        f" * spec: {spec.name}   manifest: {spec.fragment.relative_to(REPO)} */",
        f"#define NETLIB_SPEC {spec.name}",
    ]
    for key, val in spec.defines.items():
        lines.append(f"#define {key} {val}")
    lines.append(f'#include "{spec.ref_c}"')
    path = RAISED / f"{spec.name}.c"
    path.write_text("\n".join(lines) + "\n")
    return path


