def build_one(spec: Spec, rec: R.Recipe, timeout: int, do_raise: bool) -> dict:
    wrapper = write_wrapper(spec)
    prefix = RAISED / spec.name
    st: dict = {"spec": spec.name, "routine": spec.routine, "wrapper": str(wrapper.relative_to(REPO))}
    if not spec.ref_c.exists():
        st.update(status="FAIL_SOURCE", reason=f"missing {spec.ref_c.relative_to(REPO)}")
        return st
    steps_json = Path(f"{prefix}.steps.json")
    if do_raise:
        for suffix in (".mlir", "_linalg.mlir", "_debuf.mlir"):
            Path(f"{prefix}{suffix}").unlink(missing_ok=True)
        res = R.raise_c(rec, str(wrapper), spec.name, str(prefix), [], timeout)
        steps = {"recipe": rec.name, "commands": [], "failure": None}
        for step in ("cgeist", "raise", "debuf"):
            r = res.get(step)
            if r is None:
                break
            steps["commands"].append(R.shell_line(r.cmd).replace(str(REPO) + "/", ""))
            if r.recovery:
                steps.setdefault('recoveries', {})[step] = r.recovery
            if not r.ok:
                steps["failure"] = {
                    "status": f"FAIL_{step.upper()}",
                    "reason": (f"timeout after {timeout}s" if r.timed_out
                               else summarize_stderr(r.stderr, r.rc)),
                    "stderr": r.stderr[-1500:]}
                break
        steps_json.write_text(json.dumps(steps, indent=1))
    steps = json.loads(steps_json.read_text()) if steps_json.exists() else {"commands": [], "failure": None}
    st["commands"] = steps.get("commands", [])
    st['recoveries'] = steps.get('recoveries', {})
    if steps.get("failure"):
        st.update(steps["failure"])
        return st
    debuf = Path(f"{prefix}_debuf.mlir")
    linalg = Path(f"{prefix}_linalg.mlir")
    if not debuf.exists():
        st.update(status="FAIL_DEBUF", reason="no debuf artifact")
        return st
    text = debuf.read_text()
    a = analyse(text, spec.name)
    st["analysis"] = a
    la = analyse(linalg.read_text(), spec.name) if linalg.exists() else {}
    st["linalg_analysis"] = la
    if a["generics"] == 0:
        st.update(status="NOT_RAISED", reason="no linalg.generic after raising"
                  + (f"; residual {', '.join(a['loops'])}" if a["loops"] else ""))
        return st
    if a["loop_count"] or a["memref_access"]:
        st.update(status="PARTIAL", reason=f"{a['generics']} linalg.generic but residual "
                  f"{', '.join(a['loops']) or 'memref load/store'} ({a['loop_count']} loop ops, "
                  f"{a['memref_access']} scalar memory accesses)")
        return st
    try:
        defn, meta = to_defn(text, spec)
    except DefnError as e:
        st.update(status="PARTIAL", reason=f"not tensor-clean: {e}")
        return st
    ok, err = verify_defn(defn)
    if not ok:
        st.update(status="FAIL_DEFN", reason=(err.strip().splitlines() or ["?"])[0][:300])
        return st
    st.update(status="RAISED", reason="", defn=defn, meta=meta)
    return st


GOOD = ("EXACT", "WITHIN_1e-12")


def validate_results(results: list[dict], specs: dict, jobs: int) -> None:
    """Numerically validate raised specs against their C transliteration
    (validate_specs.py).  RAISED specs whose kernel.defn semantics disagree
    with the C source become UNSOUND; specs that cannot be executed become
    UNVALIDATED.  Neither enters kernel_library_v2.mlir."""
    import validate_specs as V
    todo = [r for r in results if r["status"] in ("RAISED", "PARTIAL", "NOT_RAISED")]

    def one(r):
        s = specs[r["spec"]]
        lds = set(vla_leading_dims(s.ref_c).keys())
        dv = V.validate(s.name, s.raw, s.ref_c, lds, "defn")
        lv = V.validate(s.name, s.raw, s.ref_c, lds, "linalg")
        av = V.validate(s.name, s.raw, s.ref_c, lds, "affine")
        return r, dv, lv, av
    with ThreadPoolExecutor(jobs) as ex:
        for r, dv, lv, av in ex.map(one, todo):
            r["validation"] = {"defn": dv.get("verdict"), "defn_maxabs": dv.get("maxabs"),
                               "linalg": lv.get("verdict"), "linalg_maxabs": lv.get("maxabs"),
                               "affine": av.get("verdict"), "affine_maxabs": av.get("maxabs")}
            if r["status"] != "RAISED":
                continue
            if dv.get("verdict") in GOOD:
                continue
            if dv.get("verdict") == "UNSOUND":
                r["status"] = "UNSOUND"
                r["reason"] = (f"raised defn disagrees with the C transliteration "
                               f"(max abs err {dv.get('maxabs'):.3g}; memref-Linalg route: "
                               f"{lv.get('verdict')})")
            else:
                r["status"] = "UNVALIDATED"
                r["reason"] = (f"defn could not be executed for validation ({dv.get('verdict')}; "
                               f"memref-Linalg route: {lv.get('verdict')}"
                               + (f", max abs err {lv.get('maxabs'):.3g}" if lv.get('maxabs') else "")
                               + ")")


def summarize_stderr(stderr: str, rc: int) -> str:
    lines = [ln.strip() for ln in stderr.strip().splitlines() if ln.strip()]
    if any("PLEASE submit a bug report" in ln for ln in lines) or rc in (-11, 139, -6, 134):
        prog = next((ln for ln in lines if ln.startswith("0.") or "Program arguments" in ln), "")
        first = next((ln for ln in lines if "error" in ln.lower() or "assert" in ln.lower()), "")
        return "tool crashed (stack dump)" + (f": {first[:200]}" if first else "")
    errs = [ln for ln in lines if "error" in ln]
    return (errs[0] if errs else (lines[-1] if lines else f"rc={rc}"))[:300]


def write_status(results: list[dict], rec: R.Recipe) -> None:
    by_status: dict[str, int] = {}
    for r in results:
        by_status[r["status"]] = by_status.get(r["status"], 0) + 1
    out = ["# lib_v2 raise status", "",
           "Generated by `scripts/correctness/lib_v2/build_lib_v2.py` "
           f"(recipe `{rec.name}`, see README \"Raising recipe\"). Do not edit by hand.", "",
           "Status legend: **RAISED** = every loop became `linalg.generic`, the "
           "debufferized function converts to a tensor-form `kernel.defn`, and the "
           "defn was numerically validated against the C transliteration "
           "(`validate_specs.py`; exact, or within 1e-12 when the raise "
           "re-associates a reduction) -- only these are emitted into "
           "`generic_solver/kernel_library_v2.mlir`; **UNSOUND** = fully raised but "
           "the raised semantics disagree with the C source; **UNVALIDATED** = fully "
           "raised but the defn could not be lowered/executed for validation; "
           "**PARTIAL** = some `linalg.generic` but residual loops / scalar memory "
           "accesses (or memref boundary not tensor-clean), so no defn; "
           "**NOT_RAISED** = no `linalg.generic`; **FAIL_<STEP>** = tool error or "
           "timeout.", "",
           "Validation columns: `defn` = the debufferized tensor function (what "
           "`--lower-kernel-launch` inlines), lowered via `legalize_tensor_submaps.py` "
           "+ the production residual lowering; `linalg` = the memref-form Linalg "
           "before debufferization, lowered with the in-tree loop path (an "
           "independent second route).  EXACT = bitwise equal on deterministic "
           "random inputs (sizes 7/5/6, padded leading dims 16, increments 2).", "",
           "Summary: " + ", ".join(f"{k}: {v}" for k, v in sorted(by_status.items()))
           + f" (total {len(results)})", "",
           "| spec | routine | status | generics | residual (debuf) | validation defn / linalg | reason |",
           "|---|---|---|---:|---|---|---|"]
    for r in results:
        a = r.get("analysis", {})
        resid = ", ".join(a.get("loops", [])) or ("-" if a else "")
        reason = r.get("reason", "").replace("|", "\\|")
        v = r.get("validation")
        vs = f"{v['defn']} / {v['linalg']}" if v else ""
        out.append(f"| `{r['spec']}` | {r['routine']} | {r['status']} | "
                   f"{a.get('generics', '')} | {resid} | {vs} | {reason} |")
    out += ["", "## Minimal reproducers for non-RAISED specs", "",
            "Each reproducer is the generated wrapper (`raised/<spec>.c`, which only "
            "`#define`s the manifest flags and `#include`s `ref_c/<routine>.c`) plus "
            "the exact recipe commands, run from the repository root after "
            "`source envsetup.sh`.", ""]
    for r in results:
        if r["status"] == "RAISED":
            continue
        out.append(f"### `{r['spec']}` -- {r['status']}")
        out.append("")
        out.append(f"Reason: {r.get('reason', '')}")
        out.append("")
        if r.get("validation"):
            out.append("Validation harness (defn route): "
                       f"`generic_solver/lib_v2/raised/validate/{r['spec']}/defn/` "
                       "(`harness.c`, `ref_wrapper.c`, `log.txt`); rerun with "
                       f"`scripts/correctness/lib_v2/validate_specs.py --only {r['spec']}`.")
            out.append("")
        out.append("```sh")
        for c in r.get("commands", []):
            out.append(c)
        out.append("```")
        if r.get("stderr"):
            out.append("")
            out.append("<details><summary>stderr tail</summary>")
            out.append("")
            out.append("```")
            out.append(r["stderr"].strip()[-1200:])
            out.append("```")
            out.append("</details>")
        out.append("")
    STATUS_MD.write_text("\n".join(out) + "\n")


def write_library(results: list[dict], rec: R.Recipe) -> None:
    out = ["// kernel_library_v2.mlir -- GENERATED by scripts/correctness/lib_v2/build_lib_v2.py.",
           "// Do not edit.  One kernel.defn per RAISED lib_v2 spec; each body is the",
           "// spec's C transliteration of the netlib reference (generic_solver/lib_v2/ref_c)",
           f"// raised with the `{rec.name}` recipe (identical to application code), with only",
           "// the memref<->tensor function boundary rewritten (to_tensor of a parameter ->",
           "// tensor parameter; to_memref+memref.copy write-back -> kernel.yield).",
           "// Each defn is preceded by a `// lib_v2-meta:` JSON line with ABI metadata",
           "// (parameter names, written outputs, VLA leading dimensions).  The matcher",
           "// derives its recognition patterns from the defn bodies only.",
           "module {"]
    for r in results:
        if r["status"] != "RAISED":
            continue
        out.append(f"  // lib_v2-meta: {json.dumps(r['meta'], sort_keys=True)}")
        out.append(r["defn"])
        out.append("")
    out.append("}")
    LIBRARY_OUT.write_text("\n".join(out) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--recipe", default="production", choices=sorted(R.RECIPES))
    ap.add_argument("-j", type=int, default=8)
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--no-raise", action="store_true",
                    help="reuse existing raised/* artifacts (re-run analysis + defn emission)")
    ap.add_argument("--no-validate", action="store_true",
                    help="skip numerical validation (NOT recommended: unvalidated specs "
                         "are then emitted into the library)")
    a = ap.parse_args()
    rec = R.RECIPES[a.recipe]
    specs = load_specs()
    if a.only:
        specs = [s for s in specs if s.name in a.only or s.routine in a.only]
    with ThreadPoolExecutor(a.j) as ex:
        results = list(ex.map(lambda s: build_one(s, rec, a.timeout, not a.no_raise), specs))
    if not a.no_validate:
        validate_results(results, {s.name: s for s in specs}, a.j)
    for r in results:
        print(f"{r['status']:12s} {r['spec']}  {r.get('reason', '')[:120]}")
    if not a.only:
        write_status(results, rec)
        write_library(results, rec)
        if not a.no_raise and not a.no_validate:
            spec_provenance.write(LIB / "import_manifest.json", specs, results,
                                  rec, LIBRARY_OUT, [R.CGEIST, R.POLYGEIST_OPT])
        else:
            # Re-analysis cannot attest that old IR came from current inputs.
            (LIB / "import_manifest.json").unlink(missing_ok=True)
        (RAISED / "build_results.json").write_text(json.dumps(
            [{k: v for k, v in r.items() if k != "defn"} for r in results], indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
