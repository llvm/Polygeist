_LOOP_RE = re.compile(r"\b(affine\.for|affine\.parallel|affine\.if|affine\.while|"
                      r"scf\.for|scf\.while|scf\.if|scf\.parallel)\b")


def function_text(text: str, fn: str) -> str | None:
    """Text of `func.func @fn` (header line through closing brace).  MLIR's
    printer emits the whole signature on one line ending with the body `{`."""
    m = re.search(rf"^[ \t]*func\.func\s+(?:\w+\s+)?@{re.escape(fn)}\(", text, re.MULTILINE)
    if not m:
        return None
    eol = text.find("\n", m.start())
    brace = text.rfind("{", m.start(), eol if eol >= 0 else len(text))
    if brace < 0:
        return None
    end = _matching(text, brace)
    return text[m.start():end + 1].lstrip()


def _matching(text: str, open_brace: int) -> int:
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    return len(text) - 1


def analyse(debuf_text: str, fn: str) -> dict:
    body = function_text(debuf_text, fn) or ""
    loops = _LOOP_RE.findall(body)
    return {
        "generics": len(re.findall(r"\blinalg\.generic\b", body)),
        "loops": sorted(set(loops)),
        "loop_count": len(loops),
        "memref_access": len(re.findall(r"\b(?:affine|memref)\.(?:load|store)\b", body)),
        "submaps": len(re.findall(r"\bpolygeist\.submap\b", body)),
    }


# ---------------------------------------------------------------------------
# kernel.defn conversion
# ---------------------------------------------------------------------------

_ALIAS_RE = re.compile(r"^(#[\w$.-]+)\s*=\s*(.+)$", re.MULTILINE)
_ALLOWED_OPS = re.compile(r"^(arith|math|tensor|linalg|polygeist|kernel)\.|^affine\.(apply|min|max)$")


def inline_aliases(module_text: str, body: str) -> str:
    aliases = {m.group(1): m.group(2).strip() for m in _ALIAS_RE.finditer(module_text)}
    if not aliases:
        return body
    pat = re.compile("|".join(re.escape(a) for a in sorted(aliases, key=len, reverse=True))
                     + r"(?![\w$.-])")
    return pat.sub(lambda m: aliases[m.group(0)], body)


def vla_leading_dims(ref_c: Path, fn_hint: str | None = None) -> dict[str, str]:
    """Leading-dimension parameters declared by C99 VLA parameters
    `double X[][ld]`: returns {ld: X}."""
    try:
        src = ref_c.read_text()
    except OSError:
        return {}
    return {m.group(2): m.group(1)
            for m in re.finditer(r"double\s+(\w+)\s*\[\s*\]\s*\[\s*(\w+)\s*\]", src)}


class DefnError(Exception):
    pass


def to_defn(debuf_text: str, spec: Spec) -> tuple[str, dict]:
    """Convert the raised+debufferized function into a tensor-form kernel.defn.

    The body is copied verbatim except for the function boundary:
      * each `%t = bufferization.to_tensor %argK` is dropped and %t is
        renamed to the (now tensor-typed) parameter;
      * each final `%m = bufferization.to_memref %v` + `memref.copy %m, %argK`
        write-back is dropped and %v is yielded as the new value of argK;
      * `return [%r]` becomes `kernel.yield <written params...>, [%r]`;
      * #map aliases are inlined; parameters are named after manifest args.
    """
    fn = function_text(debuf_text, spec.name)
    if fn is None:
        raise DefnError("function not found in debuf output")
    sig_m = re.match(rf"func\.func\s+(?:\w+\s+)?@{re.escape(spec.name)}\((.*?)\)\s*(->\s*([^{{]*?))?\s*(attributes\s*\{{.*?\}})?\s*\{{",
                     fn, re.DOTALL)
    if not sig_m:
        raise DefnError("cannot parse function signature")
    params = []
    for piece in re.finditer(r"(%[\w]+)\s*:\s*([^,]+(?:<[^>]*>)?)", sig_m.group(1)):
        params.append((piece.group(1), piece.group(2).strip()))
    ret_types = [t.strip() for t in (sig_m.group(3) or "").strip().strip("()").split(",") if t.strip()]
    if spec.args and len(spec.args) != len(params):
        raise DefnError(f"manifest lists {len(spec.args)} args but the raised function has {len(params)}")
    names = spec.args or [p[0][1:] for p in params]
    body = fn[sig_m.end():fn.rfind("}")]
    body_lines = body.split("\n")
    existing = set(re.findall(r"%[\w]+", body))
    pname = {}
    for (old, ty), nm in zip(params, names):
        new = f"%{nm}"
        if new in existing:
            new = f"%p_{nm}"
        pname[old] = new
    rename: dict[str, str] = {}
    new_types = {}
    outputs: list[tuple[str, str]] = []   # (param, value)
    keep: list[str] = []
    to_memref: dict[str, str] = {}
    for ln in body_lines:
        s = ln.strip()
        m = re.match(r"(%[\w]+)\s*=\s*bufferization\.to_tensor\s+(%[\w]+)(?:\s+restrict)?(?:\s+writable)?\s*:\s*(\S+)", s)
        if m and m.group(2) in pname:
            if m.group(2) in rename.values():
                raise DefnError(f"parameter {m.group(2)} converted to tensor twice")
            rename[m.group(1)] = pname[m.group(2)]
            new_types[m.group(2)] = m.group(3).replace("memref<", "tensor<")
            continue
        m = re.match(r"(%[\w]+)\s*=\s*bufferization\.to_memref\s+(%[\w]+)\s*:\s*(\S+)", s)
        if m:
            to_memref[m.group(1)] = m.group(2)
            continue
        m = re.match(r"memref\.copy\s+(%[\w]+)\s*,\s*(%[\w]+)\s*:", s)
        if m and m.group(1) in to_memref and m.group(2) in pname:
            outputs.append((m.group(2), to_memref.pop(m.group(1))))
            continue
        m = re.match(r"return\b(.*)$", s)
        if m:
            rets = [t.strip() for t in m.group(1).split(":")[0].split(",") if t.strip()]
            keep.append(("__RETURN__", rets))
            continue
        keep.append(ln)
    if to_memref:
        raise DefnError(f"to_memref values not written back to a parameter: {sorted(to_memref)}")
    # Remaining body must not touch memref params or contain memref/loop ops.
    text_lines = [k for k in keep if isinstance(k, str)]
    joined = "\n".join(text_lines)
    for old, ty in params:
        if ty.startswith("memref<") and re.search(rf"{re.escape(old)}(?![\w])", joined):
            raise DefnError(f"parameter {old} is still used in memref form")
    for ln in text_lines:
        s = ln.strip()
        mm = re.match(r"(?:%[\w:#]+\s*=\s*)?([a-z_]+\.[a-zA-Z_.]+)", s)
        if mm and not _ALLOWED_OPS.match(mm.group(1)) and not s.startswith("^"):
            raise DefnError(f"non-tensor op remains: {mm.group(1)}")
    # Order outputs by parameter order.
    order = {old: i for i, (old, _) in enumerate(params)}
    outputs.sort(key=lambda pv: order[pv[0]])
    if len({p for p, _ in outputs}) != len(outputs):
        raise DefnError("a parameter is written back twice")

    def subst(line: str) -> str:
        def rep(m):
            tok = m.group(0)
            if tok in rename:
                return rename[tok]
            if tok in pname:
                return pname[tok]
            return tok
        return re.sub(r"%[\w]+(?![\w])", rep, line)

    out_body = []
    yield_vals, yield_types = [], []
    for old, val in outputs:
        yield_vals.append(subst(val))
        yield_types.append(new_types.get(old) or dict(params)[old].replace("memref<", "tensor<"))
    for k in keep:
        if isinstance(k, tuple):
            rets = [subst(r) for r in k[1]]
            vals = yield_vals + rets
            tys = yield_types + ret_types
            if vals:
                out_body.append(f"    kernel.yield {', '.join(vals)} : {', '.join(tys)}")
            else:
                out_body.append("    kernel.yield")
        else:
            out_body.append(subst(k))
    sig = []
    for old, ty in params:
        if ty.startswith("memref<"):
            ty = ty.replace("memref<", "tensor<")
        sig.append(f"{pname[old]}: {ty}")
    res_types = yield_types + ret_types
    res = ""
    if len(res_types) == 1:
        res = f" -> {res_types[0]}"
    elif res_types:
        res = f" -> ({', '.join(res_types)})"
    body_text = inline_aliases(debuf_text, "\n".join(out_body))
    defn = f"  kernel.defn @{spec.name}({', '.join(sig)}){res} {{{body_text}\n  }}"
    # Metadata used by the matcher for ABI completion (not for recognition).
    used = set(re.findall(r"%[\w]+", body_text))
    meta = {
        "spec": spec.name,
        "params": [pname[o][1:] for o, _ in params],
        "outputs": [pname[o][1:] for o, _ in outputs],
        "returns": ret_types,
        "leading_dims": {ld: arr for ld, arr in vla_leading_dims(spec.ref_c).items()
                         if f"%{ld}" in [pname[o] for o, _ in params]},
        "unreferenced": [pname[o][1:] for o, _ in params if pname[o] not in used],
    }
    return defn, meta


def verify_defn(defn: str) -> tuple[bool, str]:
    with tempfile.NamedTemporaryFile("w", suffix=".mlir", delete=False) as fh:
        fh.write("module {\n" + defn + "\n}\n")
        path = fh.name
    r = R.run([R.POLYGEIST_OPT, path, "-o", "/dev/null"], 60)
    Path(path).unlink(missing_ok=True)
    return r.ok, r.stderr


