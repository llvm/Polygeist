#!/usr/bin/env python3
"""Translation validation of lib_v2 specifications.

For every spec in <spec-dir>/manifest/*.json, derive the element-equation
system of the cgeist (affine) stage -- the faithful semantics of the C
transliteration -- and of the debufferized stage that application code is
matched in, and check them for equality with the region matcher's egglog
comparison (identity binding).  Writes a Markdown table.

usage: translation_validate.py --spec-dir generic_solver/lib_v2 [--out FILE.md]
"""
from __future__ import annotations

import argparse
import os
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_HERE))

from region_match.matcher import load_specs  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec-dir", required=True)
    ap.add_argument("--out")
    a = ap.parse_args()
    notes: list[str] = []
    t0 = time.perf_counter()
    specs = load_specs(a.spec_dir, notes.append)
    ms = (time.perf_counter() - t0) * 1000
    rows = ["| spec | equations | semantics stage | debufferized stage vs cgeist stage |",
            "|---|---:|---|---|"]
    bad = 0
    for s in specs:
        v = s.validation.replace("|", "\\|")
        if "NOT equivalent" in v:
            bad += 1
        rows.append(f"| `{s.name}` | {len(s.system.equations)} | {s.source_stage} | {v[:400]} |")
    for n in notes:
        rows.append(f"| {n.split(':')[0].replace('spec ', '`') + '`'} | - | not analysable | "
                    f"{n.split(':', 1)[1].strip()[:300].replace('|', '/')} |")
    text = "\n".join([
        "# lib_v2 translation validation (region matcher)", "",
        f"{len(specs)} specs analysable, {len(notes)} not analysable, {bad} with a debufferized "
        f"stage that is NOT equivalent to the cgeist stage; {ms:.0f} ms.", "",
        "Generated by `scripts/correctness/region_match/translation_validate.py`.", "", *rows, ""])
    if a.out:
        open(a.out, "w").write(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
